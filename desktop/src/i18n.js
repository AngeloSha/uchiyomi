const LANGS = Object.keys(S);

/** The shell language for an OS locale like `de-AT`, `pt-PT`, `zh-Hant-TW`: the nearest one we have. */
function pickLang(locale) {
  const l = String(locale || '').toLowerCase();
  if (l.startsWith('pt')) return 'pt-BR';
  const two = l.slice(0, 2);
  return LANGS.includes(two) ? two : 'en';
}

/** @param {string} lang */
function translator(lang) {
  const d = S[lang] || S.en;
  /** @param {string} key @param {Record<string, string | number>} [vars] */
  return (key, vars = {}) => {
    const t = d[key] ?? S.en[key] ?? key;
    return t.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  };
}

/** The strings a local page needs, as one object (passed to the page through the preload). */
function pageStrings(lang, prefix) {
  const t = translator(lang);
  return Object.fromEntries(Object.keys(S.en).filter((k) => k.startsWith(prefix)).map((k) => [k, t(k)]));
}

const isRtl = (lang) => lang === 'ar';

module.exports = { S, LANGS, pickLang, translator, pageStrings, isRtl };
